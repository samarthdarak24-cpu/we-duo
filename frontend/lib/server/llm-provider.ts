// ---------------------------------------------------------------------------
// LLM investigation narrative provider (Phase 9).
//
// Deterministic evidence-only text is the source of truth and remains available
// when TD_LLM_PROVIDER=none. An optional provider (local transformers or a
// remote endpoint) may summarize known findings but MUST NOT fabricate vehicle
// records or override verified database facts. AI-generated narratives are
// clearly labelled and cite evidence IDs.
// ---------------------------------------------------------------------------
import { createHash } from "node:crypto";

export interface LLMNarrativeRequest {
  vehicleId: string;
  findings: Array<{ id: string; code: string; title: string; explanation: string; severity: string }>;
  evidenceIds: string[];
  language?: string;
}

export interface LLMNarrativeResponse {
  narrative: string;
  provider: string;
  labelledAI: boolean;
  evidenceIds: string[];
  model?: string;
}

export interface LLMProvider {
  name: string;
  configured: boolean;
  summarize(request: LLMNarrativeRequest): Promise<LLMNarrativeResponse>;
}

/** Deterministic evidence-only fallback. Always available. Never an LLM. */
export class DeterministicProvider implements LLMProvider {
  name = "deterministic";
  configured = true;

  summarize(request: LLMNarrativeRequest): Promise<LLMNarrativeResponse> {
    const lines = [
      `TrustDrive investigation narrative for vehicle ${request.vehicleId}.`,
      "This report is generated by deterministic rules from verified database records.",
      "No LLM was used to produce this narrative.",
      "",
      `Findings (${request.findings.length}):`,
    ];
    for (const f of request.findings) {
      lines.push(`- [${f.id}] ${f.title}: ${f.explanation} (severity: ${f.severity})`);
    }
    if (request.evidenceIds.length) {
      lines.push("");
      lines.push("Evidence referenced: " + request.evidenceIds.join(", "));
    }
    lines.push("");
    lines.push("Missing data is unverified coverage, not proof of fraud.");
    lines.push("State of Health is never inferred from odometer or photographs.");

    return Promise.resolve({
      narrative: lines.join("\n"),
      provider: "deterministic",
      labelledAI: false,
      evidenceIds: request.evidenceIds,
    });
  }
}

/** Optional LLM provider (local transformers or remote endpoint). */
export class LlmProvider implements LLMProvider {
  name = "llm";
  configured: boolean;
  readonly provider: string | null;
  readonly model: string | null;
  readonly baseUrl: string | null;
  readonly apiKey: string | null;

  constructor() {
    this.provider = process.env.TD_LLM_PROVIDER ?? null;
    this.model = process.env.TD_LLM_MODEL ?? null;
    this.baseUrl = process.env.TD_LLM_BASE_URL ?? null;
    this.apiKey = process.env.TD_LLM_API_KEY ?? null;
    this.configured = Boolean(this.provider && this.provider !== "none" && this.provider !== "deterministic");
  }

  async summarize(request: LLMNarrativeRequest): Promise<LLMNarrativeResponse> {
    if (!this.configured || !this.baseUrl || !this.model) {
      return new DeterministicProvider().summarize(request);
    }
    try {
      const res = await fetch(`${this.baseUrl}/chat/completions`, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${this.apiKey ?? ""}`,
        },
        body: JSON.stringify({
          model: this.model,
          messages: [
            {
              role: "system",
              content: "You are a TrustDrive investigator. Summarize ONLY the provided findings. Never invent vehicle records, VINs, or damage. Cite evidence IDs. Label output as AI-generated.",
            },
            {
              role: "user",
              content: JSON.stringify(request),
            },
          ],
          max_tokens: Number(process.env.TD_LLM_MAX_NEW_TOKENS) || 220,
        }),
        signal: AbortSignal.timeout(15_000),
      });
      if (!res.ok) {
        return new DeterministicProvider().summarize(request);
      }
      const body = await res.json();
      const text = body.choices?.[0]?.message?.content ?? "";
      return {
        narrative: `[AI-generated summary]\n${text}`,
        provider: this.provider ?? "llm",
        labelledAI: true,
        evidenceIds: request.evidenceIds,
        model: this.model ?? undefined,
      };
    } catch {
      return new DeterministicProvider().summarize(request);
    }
  }
}

let _provider: LLMProvider | null = null;

export function getLLMProvider(): LLMProvider {
  if (_provider) return _provider;
  const llm = new LlmProvider();
  _provider = llm.configured ? llm : new DeterministicProvider();
  return _provider;
}

export function getLLMStatus() {
  const llm = new LlmProvider();
  if (llm.configured) {
    return { provider: llm.provider, configured: true, model: llm.model };
  }
  return { provider: "deterministic", configured: true, model: null, note: "Deterministic evidence-only narrative; no LLM provider configured." };
}

export async function summarizeInvestigation(request: LLMNarrativeRequest): Promise<LLMNarrativeResponse> {
  return getLLMProvider().summarize(request);
}
