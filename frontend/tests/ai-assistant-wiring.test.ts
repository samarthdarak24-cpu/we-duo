import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";

import { POST } from "../app/api/v1/ai/assistant/route";

// The assistant is the ONLY user-facing path to the grounded LLM. These tests
// pin the assistant -> /api/intelligence/chat wiring: a validated narrative is
// shown, a rejected narrative is never presented as an LLM result, and a dead
// intelligence service degrades to the deterministic evidence-only answer.
const question = "Summarise the mileage anomaly and missing documents.";
const vehicleId = "v-camry"; // published listing: the route is public for it

function request() {
  return new Request("http://127.0.0.1:3000/api/v1/ai/assistant", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ question, vehicleId }),
  });
}

function intelligenceResponse(payload: unknown, status = 200) {
  return new Response(JSON.stringify(payload), {
    status,
    headers: { "Content-Type": "application/json" },
  });
}

describe("assistant -> grounded LLM wiring", () => {
  beforeEach(() => {
    vi.stubEnv("TD_INTELLIGENCE_URL", "http://127.0.0.1:8000");
    vi.stubEnv("TD_INTELLIGENCE_TIMEOUT_MS", "90000");
    vi.stubEnv("TD_SERVICE_TOKEN", "");
  });

  afterEach(() => {
    vi.unstubAllEnvs();
    vi.unstubAllGlobals();
    vi.restoreAllMocks();
  });

  it("uses the validated LLM narrative and names the active engine", async () => {
    const fetchMock = vi.fn().mockResolvedValue(intelligenceResponse({
      answer: "The mileage decreased between the 2022 and 2023 readings. Sources: m-b1, v-camry.",
      grounded: true,
      provider: "local-transformers",
      model: "Qwen/Qwen2.5-0.5B-Instruct",
      llm_rejected: false,
      reason: "Grounded in supplied evidence.",
      citations: [{ kind: "vehicle", id: "v-camry", label: "Toyota Camry", detail: "Registration MH12CD8899" }],
    }));
    vi.stubGlobal("fetch", fetchMock);

    const res = await POST(request());
    expect(res.status).toBe(200);
    const { data } = await res.json();

    expect(fetchMock).toHaveBeenCalledOnce();
    expect(fetchMock.mock.calls[0][0]).toBe("http://127.0.0.1:8000/api/intelligence/chat");
    expect(JSON.parse(fetchMock.mock.calls[0][1].body)).toEqual({ question, vehicle_id: vehicleId });
    expect(data.answer).toContain("Sources:");
    expect(data.intent).toBe("llm_grounded");
    expect(data.model).toBe("llm:local-transformers:Qwen/Qwen2.5-0.5B-Instruct");
    expect(data.provider).toBe("local-transformers");
    expect(data.grounded).toBe(true);
    expect(data.llmRejected).toBe(false);
    expect(data.citations[0].id).toBe("v-camry");
    expect(data.disclaimer).toContain("validated against stored records");
    // The trust score is deterministic; the LLM never sets it.
    expect(data.confidence).toBe(0.85);
  });

  it("falls back without claiming an LLM when the narrative is rejected", async () => {
    vi.stubGlobal("fetch", vi.fn().mockResolvedValue(intelligenceResponse({
      answer: "Trust score 86/100. Sources: v-camry.",
      grounded: true,
      provider: "deterministic",
      model: "rules-v1",
      llm_rejected: true,
      reason: "Rejected: the model made a safety judgement.",
      unsupported_claims: ["policy:safe to buy"],
      citations: [],
    })));

    const res = await POST(request());
    const { data } = await res.json();
    expect(res.status).toBe(200);
    expect(data.model).toBe("rules-v1");
    expect(data.provider).toBe("deterministic");
    expect(data.llmRejected).toBe(true);
    expect(data.disclaimer).not.toContain("Narrative generated by an LLM");
    expect(data.answer).toContain("Sources:");
  });

  it("keeps the deterministic answer when the intelligence service is down", async () => {
    vi.stubGlobal("fetch", vi.fn().mockRejectedValue(new Error("ECONNREFUSED")));

    const res = await POST(request());
    const { data } = await res.json();
    expect(res.status).toBe(200);
    expect(data.model).toBe("grounded-rules-v1");
    expect(data.answer.length).toBeGreaterThan(20);
    expect(data.citations.length).toBeGreaterThan(0);
  });

  it("does not call the intelligence service when TD_INTELLIGENCE_URL is unset", async () => {
    vi.stubEnv("TD_INTELLIGENCE_URL", "");
    const fetchMock = vi.fn();
    vi.stubGlobal("fetch", fetchMock);

    const res = await POST(request());
    const { data } = await res.json();
    expect(res.status).toBe(200);
    expect(data.model).toBe("grounded-rules-v1");
    expect(fetchMock).not.toHaveBeenCalled();
  });
});
